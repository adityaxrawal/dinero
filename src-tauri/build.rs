//! Cargo build script.
//!
//! Runs `tauri_build`, which generates the context the application embeds --
//! bundled frontend assets, the capability/permission manifest, and platform
//! resources. Without it `tauri::generate_context!` has nothing to expand.
/// Runs the Tauri build step and regenerates the bank template list.
fn main() {
    println!("cargo:rerun-if-changed=../.env");
    let env_path = std::path::Path::new("../.env");
    if env_path.exists() {
        if let Ok(contents) = std::fs::read_to_string(env_path) {
            for line in contents.lines() {
                let line = line.trim();
                if let Some(stripped) = line.strip_prefix("export ") {
                    let parts: Vec<&str> = stripped.splitn(2, '=').collect();
                    if parts.len() == 2 {
                        let key = parts[0].trim();
                        let value = parts[1].trim().trim_matches('"').trim_matches('\'');
                        println!("cargo:rustc-env={}={}", key, value);
                    }
                } else if !line.starts_with('#') && line.contains('=') {
                    let parts: Vec<&str> = line.splitn(2, '=').collect();
                    if parts.len() == 2 {
                        let key = parts[0].trim();
                        let value = parts[1].trim().trim_matches('"').trim_matches('\'');
                        println!("cargo:rustc-env={}={}", key, value);
                    }
                }
            }
        }
    }
    generate_bank_template_list();
    let commands = registered_app_commands();
    write_app_command_capability(&commands);
    let commands: &'static [&'static str] =
        Box::leak(commands.into_iter().map(|c| &*Box::leak(c.into_boxed_str())).collect::<Vec<_>>().into_boxed_slice());
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("tauri build failed");
}

/// Every app command registered in `commands::get_handlers`.
///
/// Read from the generate_handler! list itself, so the permission set cannot
/// drift from what is actually registered (review M11 follow-up).
fn registered_app_commands() -> Vec<String> {
    println!("cargo:rerun-if-changed=src/commands/mod.rs");
    let src = std::fs::read_to_string("src/commands/mod.rs").expect("read src/commands/mod.rs");
    let start = src.find("tauri::generate_handler![").expect("generate_handler! list");
    let list = &src[start + "tauri::generate_handler![".len()..];
    // The list closes on a line holding only "]" (attributes like
    // #[cfg(debug_assertions)] contain brackets too).
    let list = &list[..list.find("\n    ]").expect("end of generate_handler! list")];
    let mut commands: Vec<String> = list
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with("//") && !l.starts_with("#["))
        .map(|l| l.trim_end_matches(',').rsplit("::").next().unwrap_or(l).to_string())
        .collect();
    commands.sort();
    commands.dedup();
    commands
}

/// Grants the registered app commands to the main window only.
///
/// With an app manifest, a command without a matching permission is denied
/// at runtime, so this capability is what keeps the UI working; scoping it to
/// the "main" window means no other window or remote origin may call them.
fn write_app_command_capability(commands: &[String]) {
    let permissions: Vec<String> = commands
        .iter()
        .map(|c| format!("\"allow-{}\"", c.replace('_', "-")))
        .collect();
    let json = format!(
        "{{\n  \"$schema\": \"../gen/schemas/desktop-schema.json\",\n  \"identifier\": \"app-commands\",\n  \"description\": \"Generated by build.rs from commands::get_handlers -- do not edit.\",\n  \"windows\": [\"main\"],\n  \"permissions\": [\n    {}\n  ]\n}}\n",
        permissions.join(",\n    ")
    );
    std::fs::create_dir_all("capabilities").expect("create capabilities dir");
    let path = "capabilities/app-commands.json";
    if std::fs::read_to_string(path).ok().as_deref() != Some(json.as_str()) {
        std::fs::write(path, json).expect("write app command capability");
    }
}

/// Generates the compile-time list of banks that ship with a template.
///
/// Derived from the template files themselves, so adding a template does not also
/// require editing a hand-maintained list that could drift out of step.
fn generate_bank_template_list() {
    let dir = std::path::Path::new("assets/bank_templates");
    println!("cargo:rerun-if-changed=assets/bank_templates");

    let mut files: Vec<String> = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("assets/bank_templates must be readable: {e}"))
        .filter_map(|entry| {
            let name = entry.ok()?.file_name().to_string_lossy().into_owned();
            name.ends_with(".json").then_some(name)
        })
        .collect();
    files.sort();

    assert!(
        !files.is_empty(),
        "assets/bank_templates contains no *.json files -- Layer 2 would silently \
         have zero templates for every bank"
    );

    let mut out = String::from("const BANK_TEMPLATE_FILES: &[(&str, &str)] = &[\n");
    for name in &files {
        out.push_str(&format!(
            "    ({name:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \
             \"/assets/bank_templates/\", {name:?}))),\n"
        ));
    }
    out.push_str("];\n");

    let dest = std::path::Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"))
        .join("bank_template_files.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("writing {dest:?} failed: {e}"));
}
